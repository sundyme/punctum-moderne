"""Build assets/social.js: the film's engine-side helpers and scenes (film.js up to its timeline),
re-dimensioned for 9:16, plus the social cut (assets/social.part.js).   python3 tools/build_social.py"""
import os
A = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets")
src = open(os.path.join(A, "film.js"), encoding="utf-8").read()
cut = src.index("  // ==================================================================== timeline")
head = src[:cut].replace("const W = 1920, H = 1080, DUR = 72, BEAT = 0.5;", "const W = 1080, H = 1920, DUR = 32, BEAT = 0.5;", 1)
assert "H = 1920" in head
part = open(os.path.join(A, "social.part.js"), encoding="utf-8").read()
open(os.path.join(A, "social.js"), "w", encoding="utf-8").write("/* PUNCTUM MODERNE — social cut (9:16, 30 s). GENERATED by tools/build_social.py — edit social.part.js */\n" + head + part)
print("assets/social.js", len(head) + len(part))
