"""PUNCTUM — glyph bitmaps.

Grid: 5 columns × 9 rows.
  rows 0–6  : above baseline (row 0 = cap/ascender top, row 6 = baseline row)
  rows 7–8  : descender
  x-height  : rows 2–6 (5 dots)
A glyph may list fewer than 9 rows; missing rows are blank.
"""

