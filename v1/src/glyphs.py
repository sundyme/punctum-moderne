ROWS, COLS = 9, 5


def normalized():
    out = {}
    for ch, rows in G.items():
        rows = list(rows) + ["....."] * (ROWS - len(rows))
        assert len(rows) == ROWS, ch
        for r in rows:
            assert len(r) == COLS and set(r) <= {".", "#"}, (ch, r)
        out[ch] = rows
    return out
